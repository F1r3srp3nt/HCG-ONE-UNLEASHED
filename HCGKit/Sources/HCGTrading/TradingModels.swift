import Foundation
import HCGDomain

// Simulated trading model for HCG ONE UNLEASHED. Every order, fill and
// position here is simulated: nothing is ever routed to an exchange, broker
// or HCG service. Prices are stored in whole ticks of the instrument.

public enum OrderSide: String, Codable, Sendable, CaseIterable, Identifiable {
    case buy, sell

    public var id: String { rawValue }
    public var label: String { rawValue.capitalized }
    public var opposite: OrderSide { self == .buy ? .sell : .buy }
    /// +1 for buys, −1 for sells.
    public var sign: Int { self == .buy ? 1 : -1 }
}

public enum OrderType: String, Codable, Sendable, CaseIterable, Identifiable {
    case market, limit, stop

    public var id: String { rawValue }
    public var label: String { rawValue.capitalized }
}

/// Order lifecycle.
///
/// - `accepted`: validated and stored, but not active in the market yet
///   (bracket take-profit/stop-loss waiting for the entry to fill).
/// - `working`: active; may fill on a later market update.
/// - `partiallyFilled`: some quantity filled, the rest still working.
/// - `filled`, `cancelled`, `rejected`: final.
public enum OrderStatus: String, Codable, Sendable, CaseIterable {
    case accepted, working, partiallyFilled, filled, cancelled, rejected

    public var label: String {
        switch self {
        case .accepted: "Accepted"
        case .working: "Working"
        case .partiallyFilled: "Partially filled"
        case .filled: "Filled"
        case .cancelled: "Cancelled"
        case .rejected: "Rejected"
        }
    }

    /// Not final: can still fill or be cancelled.
    public var isOpen: Bool { self == .accepted || self == .working || self == .partiallyFilled }
}

/// Why an order exists.
public enum OrderRole: String, Codable, Sendable {
    /// Opens, adds to or reduces a position as the user entered it.
    case entry
    /// Reduce-only profit target (bracket or position protection).
    case takeProfit
    /// Reduce-only protective stop (bracket or position protection).
    case stopLoss
    /// Market order generated by "close position" / "flatten".
    case close

    public var label: String {
        switch self {
        case .entry: "Entry"
        case .takeProfit: "Take profit"
        case .stopLoss: "Stop loss"
        case .close: "Close"
        }
    }

    public var isReduceOnly: Bool { self != .entry }
}

/// Take-profit and stop-loss distances, in ticks from the entry's average
/// fill price. At least one must be set.
public struct BracketSpec: Codable, Hashable, Sendable {
    public var takeProfitTicks: Int?
    public var stopLossTicks: Int?

    public init(takeProfitTicks: Int? = nil, stopLossTicks: Int? = nil) {
        self.takeProfitTicks = takeProfitTicks
        self.stopLossTicks = stopLossTicks
    }
}

/// What the user asks for. Prices are in instrument price units and must lie
/// on the instrument's tick grid.
public struct OrderRequest: Codable, Hashable, Sendable {
    /// Caller-chosen idempotency key: a second request with the same key is
    /// rejected as a duplicate.
    public var clientOrderID: String
    public var symbol: MarketSymbol
    public var side: OrderSide
    public var type: OrderType
    public var quantity: Int
    /// Required for limit orders.
    public var limitPrice: Double?
    /// Required for stop orders (trigger price).
    public var stopPrice: Double?
    /// Optional take-profit / stop-loss attached to the entry.
    public var bracket: BracketSpec?

    public init(clientOrderID: String = UUID().uuidString, symbol: MarketSymbol, side: OrderSide,
                type: OrderType, quantity: Int, limitPrice: Double? = nil, stopPrice: Double? = nil,
                bracket: BracketSpec? = nil) {
        self.clientOrderID = clientOrderID
        self.symbol = symbol
        self.side = side
        self.type = type
        self.quantity = quantity
        self.limitPrice = limitPrice
        self.stopPrice = stopPrice
        self.bracket = bracket
    }

    public static func market(_ side: OrderSide, _ quantity: Int, _ symbol: MarketSymbol,
                              id: String = UUID().uuidString, bracket: BracketSpec? = nil) -> OrderRequest {
        OrderRequest(clientOrderID: id, symbol: symbol, side: side, type: .market, quantity: quantity, bracket: bracket)
    }

    public static func limit(_ side: OrderSide, _ quantity: Int, _ symbol: MarketSymbol, at price: Double,
                             id: String = UUID().uuidString, bracket: BracketSpec? = nil) -> OrderRequest {
        OrderRequest(clientOrderID: id, symbol: symbol, side: side, type: .limit, quantity: quantity,
                     limitPrice: price, bracket: bracket)
    }

    public static func stop(_ side: OrderSide, _ quantity: Int, _ symbol: MarketSymbol, at price: Double,
                            id: String = UUID().uuidString, bracket: BracketSpec? = nil) -> OrderRequest {
        OrderRequest(clientOrderID: id, symbol: symbol, side: side, type: .stop, quantity: quantity,
                     stopPrice: price, bracket: bracket)
    }
}

/// An order as tracked by the simulated account.
public struct Order: Identifiable, Codable, Hashable, Sendable {
    public let id: Int
    public let clientOrderID: String
    public let symbol: MarketSymbol
    public let side: OrderSide
    public let type: OrderType
    public let role: OrderRole
    public internal(set) var quantity: Int
    public internal(set) var limitTicks: Int64?
    public internal(set) var stopTicks: Int64?
    /// Entry order this take-profit/stop-loss belongs to.
    public let parentID: Int?
    /// Orders sharing an OCO group cancel each other.
    public let ocoGroup: Int?
    public let bracket: BracketSpec?
    public internal(set) var status: OrderStatus
    public internal(set) var filledQuantity = 0
    /// Volume-weighted average of this order's fills.
    public internal(set) var averageFillPrice: Double?
    /// Rejection or cancellation reason, shown to the user.
    public internal(set) var statusReason: String?
    public let createdSequence: Int
    public let createdAt: Date
    public internal(set) var updatedSequence: Int
    public internal(set) var updatedAt: Date

    public var remainingQuantity: Int { max(0, quantity - filledQuantity) }
    public var isOpen: Bool { status.isOpen }

    public func limitPrice(_ spec: InstrumentSpec) -> Double? { limitTicks.map(spec.price(ticks:)) }
    public func stopPrice(_ spec: InstrumentSpec) -> Double? { stopTicks.map(spec.price(ticks:)) }
}

/// Whether a fill took liquidity (market, stop, marketable limit) or rested
/// until the market reached it (resting limit).
public enum Liquidity: String, Codable, Sendable {
    case taker, maker
}

/// One simulated execution.
public struct Fill: Identifiable, Codable, Hashable, Sendable {
    public let id: Int
    public let orderID: Int
    public let symbol: MarketSymbol
    public let side: OrderSide
    public let quantity: Int
    /// Volume-weighted price of this fill, including slippage.
    public let price: Double
    public let commission: Double
    public let fees: Double
    public let liquidity: Liquidity
    /// Gross P&L realised by this fill (before commission and fees).
    public let realizedPnL: Double
    public let sequence: Int
    public let time: Date
}

/// One aggregated position per market. Quantity is signed: + long, − short.
public struct Position: Codable, Hashable, Sendable, Identifiable {
    public let symbol: MarketSymbol
    public internal(set) var quantity: Int
    public internal(set) var averagePrice: Double
    /// Commission and fees paid on the contracts still open, used to report
    /// round-trip net P&L when they are closed.
    public internal(set) var openCosts: Double
    public internal(set) var openedSequence: Int
    public internal(set) var openedAt: Date

    public var id: MarketSymbol { symbol }
    public var isLong: Bool { quantity > 0 }
    public var isFlat: Bool { quantity == 0 }
    public var side: OrderSide { quantity >= 0 ? .buy : .sell }
}

/// A completed round trip (or the closed part of one).
public struct TradeRecord: Identifiable, Codable, Hashable, Sendable {
    public enum Direction: String, Codable, Sendable { case long, short }

    public let id: Int
    public let symbol: MarketSymbol
    public let direction: Direction
    public let quantity: Int
    public let entryPrice: Double
    public let exitPrice: Double
    public let entryTime: Date
    public let exitTime: Date
    public let grossPnL: Double
    /// Entry and exit commission plus fees attributable to this quantity.
    public let costs: Double

    public var netPnL: Double { grossPnL - costs }
}

/// Entry in the account's activity log (shown as "recent activity").
public struct AccountEvent: Identifiable, Codable, Hashable, Sendable {
    public enum Kind: String, Codable, Sendable {
        case orderAccepted, orderWorking, orderPartiallyFilled, orderFilled, orderCancelled, orderRejected
        case accountReset, configurationChanged
    }

    public let id: Int
    public let kind: Kind
    public let orderID: Int?
    public let symbol: MarketSymbol?
    public let message: String
    public let sequence: Int
    public let time: Date
}

/// Result of submitting an order.
public struct OrderResult: Sendable, Equatable {
    /// The order as stored (status may be `rejected`).
    public let order: Order
    /// Fills produced immediately (market or marketable limit orders).
    public let fills: [Fill]

    public var isAccepted: Bool { order.status != .rejected }
}
