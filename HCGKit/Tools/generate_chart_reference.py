#!/usr/bin/env python3
"""Generates HCGKit/Tests/HCGChartingTests/ReferenceData.swift.

Reference values for the charting tests come from independent tools, not
from the Swift code under test:

* indicators (SMA, EMA, RSI, MACD, Bollinger Bands, ATR): TA-Lib;
* candle aggregation for every timeframe and session VWAP: pandas
  (`resample` with epoch origin; 4h and 1D offset to the 22:00 UTC session).

The inputs are deterministic (fixed NumPy seeds), so regenerating produces
the same file.

Usage (TA-Lib's Python package bundles the C library):

    python3 -m venv /tmp/ref && /tmp/ref/bin/pip install ta-lib numpy pandas
    /tmp/ref/bin/python HCGKit/Tools/generate_chart_reference.py
"""
import math
import pathlib

import numpy as np
import pandas as pd
import talib

OUT = pathlib.Path(__file__).resolve().parent.parent / "Tests" / "HCGChartingTests" / "ReferenceData.swift"


def lit(x):
    """Swift literal for a float (shortest round-trip repr) or nil."""
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "nil"
    return repr(float(x))


def arr(values, per_line=6):
    items = [lit(v) for v in values]
    lines = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    return "[\n        " + ",\n        ".join(lines) + ",\n    ]"


# --- Indicator input: 150 candles in ticks (ES-like random walk). -----------
rng = np.random.default_rng(20261031)
n = 150
close = np.empty(n)
price = 21_920.0
for i in range(n):
    price += float(rng.integers(-6, 7))
    close[i] = price
open_ = np.concatenate([[close[0] - 1], close[:-1]])
high = np.maximum(open_, close) + rng.integers(0, 5, n)
low = np.minimum(open_, close) - rng.integers(0, 5, n)

sma20 = talib.SMA(close, 20)
ema9 = talib.EMA(close, 9)
ema21 = talib.EMA(close, 21)
rsi14 = talib.RSI(close, 14)
macd, macd_signal, macd_hist = talib.MACD(close, 12, 26, 9)
bb_upper, bb_middle, bb_lower = talib.BBANDS(close, 20, 2, 2, 0)
atr14 = talib.ATR(high, low, close, 14)

# --- Trade input: 1,500 trades from 20:30 UTC across the 22:00 session open.
trng = np.random.default_rng(7_340)
start = pd.Timestamp("2026-01-05 20:30:00", tz="UTC").timestamp()  # 20:30 UTC
t = start + np.cumsum(trng.exponential(7.0, 1_500))
t = np.round(t, 3)
ticks = 21_920 + np.cumsum(trng.integers(-2, 3, 1_500))
size = trng.integers(1, 21, 1_500)
side = np.where(trng.random(1_500) < 0.5, "buy", "sell")

df = pd.DataFrame({
    "price": ticks.astype(float),
    "size": size,
    "buy": np.where(side == "buy", size, 0),
    "sell": np.where(side == "sell", size, 0),
    "notional": ticks * size,
}, index=pd.to_datetime(t, unit="s"))  # naive UTC: pandas applies origin/offset to 1D only when naive

frames = {"m1": "1min", "m5": "5min", "m15": "15min", "h1": "1h", "h4": "4h", "d1": "1D"}
offsets = {"h4": "22h", "d1": "22h"}
candles = {}
for key, rule in frames.items():
    r = df.resample(rule, origin="epoch", offset=offsets.get(key))
    c = pd.DataFrame({
        "open": r["price"].first(), "high": r["price"].max(), "low": r["price"].min(),
        "close": r["price"].last(), "volume": r["size"].sum(), "buy": r["buy"].sum(),
        "sell": r["sell"].sum(), "trades": r["price"].count(), "notional": r["notional"].sum(),
    })
    candles[key] = c[c["trades"] > 0]

# Session VWAP at each 1m and 5m candle close (session opens 22:00 UTC).
def session_vwap(c):
    seconds = (c.index - pd.Timestamp("1970-01-01")) // pd.Timedelta(seconds=1)
    session = (seconds - 22 * 3600) // 86_400
    g = c.groupby(session)
    return (g["notional"].cumsum() / g["volume"].cumsum()).to_numpy()

vwap_m1 = session_vwap(candles["m1"])
vwap_m5 = session_vwap(candles["m5"])

# --- Emit Swift. --------------------------------------------------------------
# Data is emitted as CSV inside string literals: large array/tuple literals
# make the Swift type checker run out of memory. The tests parse the CSV.
def csv_line(values):
    return ",".join("" if (v is None or (isinstance(v, float) and math.isnan(v))) else repr(float(v)) for v in values)

out = []
out.append("// GENERATED by HCGKit/Tools/generate_chart_reference.py. Do not edit.")
out.append(f"// TA-Lib {talib.__version__}, pandas {pd.__version__}, NumPy {np.__version__}.")
out.append("enum ReferenceCSV {")
out.append("    /// One row per candle: open, high, low, close (ticks).")
out.append('    static let ohlc = """')
for row in zip(open_, high, low, close):
    out.append(csv_line(row))
out.append('"""')
out.append("    /// One row per candle (empty = warming up): sma20, ema9, ema21, rsi14, macd, macdSignal, macdHistogram,")
out.append("    /// bollingerUpper, bollingerMiddle, bollingerLower, atr14. Source: TA-Lib.")
out.append('    static let indicators = """')
for row in zip(sma20, ema9, ema21, rsi14, macd, macd_signal, macd_hist, bb_upper, bb_middle, bb_lower, atr14):
    out.append(csv_line(row))
out.append('"""')
out.append("    /// Trades: epoch seconds, price ticks, size, side (b/s).")
out.append('    static let trades = """')
for ti, p, sz, sd in zip(t, ticks, size, side):
    out.append(f"{repr(float(ti))},{int(p)},{int(sz)},{sd[0]}")
out.append('"""')
out.append("    /// pandas candles: timeframe, start epoch s, open, high, low, close, volume, buy, sell, trades, notional.")
out.append('    static let candles = """')
for key, c in candles.items():
    for ts, row in c.iterrows():
        out.append(f"{key},{repr(float(ts.tz_localize('UTC').timestamp()))},{int(row.open)},{int(row.high)},{int(row.low)},{int(row.close)},"
                   f"{int(row.volume)},{int(row.buy)},{int(row.sell)},{int(row.trades)},{repr(float(row.notional))}")
out.append('"""')
out.append("    /// pandas session VWAP (ticks) at each 1m candle close, then each 5m candle close: timeframe, value.")
out.append('    static let sessionVWAP = """')
for v in vwap_m1:
    out.append(f"m1,{repr(float(v))}")
for v in vwap_m5:
    out.append(f"m5,{repr(float(v))}")
out.append('"""')
out.append("}")
OUT.write_text("\n".join(out) + "\n")
print(f"wrote {OUT} ({OUT.stat().st_size:,} bytes); candles:", {k: len(v) for k, v in candles.items()})
